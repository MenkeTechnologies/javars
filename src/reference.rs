//! The javars language-reference corpus.
//!
//! One entry per name the current javars build actually implements, as
//! `(name, chapter, signature, doc, example)`. This is the single source of
//! truth for three consumers:
//!
//!   * the LSP completion and hover providers ([`crate::lsp`]),
//!   * the offline `docs/reference.html` generator (`src/bin/gen_docs.rs`),
//!   * and, by construction, the claim that the editor tooling and the published
//!     reference never drift from the runtime.
//!
//! Every entry is written from the implementation it documents, and each chapter
//! names the table it was read from:
//!
//! | Chapter | Source of truth |
//! | --- | --- |
//! | Keywords | `lexer.rs` `keyword_or_ident` |
//! | Contextual Keywords | `parser.rs` (identifier-matched words) |
//! | Literals | `lexer.rs` `lex` |
//! | Types | `compiler.rs` `numeric_rank` / `is_reference_type` |
//! | Operators | `lexer.rs` `Tok`, `ast.rs` `BinOp` / `UnOp` |
//! | Console IO | `host.rs` `JPRINTLN` / `JPRINT` / `JEPRINTLN` / `JEPRINT` |
//! | String Methods | `host.rs` `string_method` |
//! | Static Library | `host.rs` `static_method` |
//! | Collection Types | `compiler.rs` `collection_kind` / `is_concrete_collection` |
//! | Collection Statics | `host.rs` `collection_static` |
//! | List / Map / Set Methods | `host.rs` `list_method` / `map_method` / `set_method` |
//! | Throwables | `prelude.rs` `THROWABLES` |
//! | Functional Interfaces | `prelude.rs` `FUNCTIONAL` |
//! | Class Members | `parser.rs` `enum_members` / `record_members`, `compiler.rs` |
//! | Method References | `compiler.rs` `desugar_method_ref` / `type_method_ref` |
//! | Format Conversions | `host.rs` `java_format` / `format_conversion` |
//! | Runtime Builtins | `host.rs` `install` / `install_debug` |
//!
//! Where javars computes something other than `java` does, the entry says so.

