// Regenerate javars's table of JDK supertypes from a real JDK.
//
//   JAVA_HOME=/path/to/jdk "$JAVA_HOME/bin/java" scripts/GenJdkSupertypes.java
//
// run from the crate root. It writes src/jdk_supertypes.rs: for every public
// class and interface (top-level, and the public members of those) in the
// packages below, its type parameters and every supertype it has — the whole
// transitive set, `Object` aside — each with its type arguments written in
// terms of the class's own type parameters (`#E`) or as concrete simple names.
// The compiler reads it to decide whether a generic call's inferred bound can
// be its target (JLS 18.5.2.1); see `Compiler::known_supertypes`.
//
// A simple name that two of the packages both declare is left out, since
// javars could not tell which one a program means.

import java.io.IOException;
import java.lang.reflect.*;
import java.net.URI;
import java.nio.file.*;
import java.util.*;
import java.util.stream.*;

public class GenJdkSupertypes {
    static final String[] PACKAGES = {
        "java.lang", "java.lang.constant", "java.io", "java.math", "java.util",
        "java.util.function", "java.util.regex", "java.util.stream",
    };

    public static void main(String[] args) throws Exception {
        FileSystem jrt = FileSystems.getFileSystem(URI.create("jrt:/"));
        Map<String, List<Class<?>>> bySimple = new TreeMap<>();
        for (String pkg : PACKAGES) {
            Path dir = jrt.getPath("/modules/java.base/" + pkg.replace('.', '/'));
            List<String> names;
            try (Stream<Path> s = Files.list(dir)) {
                names = s.map(p -> p.getFileName().toString())
                        .filter(n -> n.endsWith(".class") && !n.contains("$") && !n.equals("package-info.class"))
                        .map(n -> pkg + "." + n.substring(0, n.length() - 6))
                        .sorted()
                        .collect(Collectors.toList());
            }
            for (String n : names) {
                Class<?> c = Class.forName(n, false, ClassLoader.getSystemClassLoader());
                if (!Modifier.isPublic(c.getModifiers())) continue;
                add(bySimple, c);
                for (Class<?> m : c.getClasses()) {
                    if (m.getEnclosingClass() == c && Modifier.isPublic(m.getModifiers())) add(bySimple, m);
                }
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("//! Generated by `scripts/GenJdkSupertypes.java` from ")
           .append(System.getProperty("java.vm.name")).append(' ')
           .append(System.getProperty("java.version")).append(" — do not edit.\n");
        out.append("//!\n//! Each entry is a JDK class or interface by simple name, its type\n");
        out.append("//! parameters, and every supertype it has (`Object` aside) with that\n");
        out.append("//! supertype's type arguments: a concrete simple name, `#P` for the\n");
        out.append("//! class's own type parameter `P`, or `?` for anything else.\n\n");
        out.append("/// One class: its simple name, its type parameters, and each supertype with\n");
        out.append("/// that supertype's type arguments.\n");
        out.append("pub type Entry = (\n    &'static str,\n    &'static [&'static str],\n    &'static [(&'static str, &'static [&'static str])],\n);\n\n");
        out.append("/// Every class, sorted by name.\n");
        out.append("#[rustfmt::skip]\n");
        out.append("pub static JDK_SUPERTYPES: &[Entry] = &[\n");
        for (Map.Entry<String, List<Class<?>>> e : bySimple.entrySet()) {
            if (e.getValue().size() != 1) continue;
            Class<?> c = e.getValue().get(0);
            Map<String, List<String>> sups = new TreeMap<>();
            collect(c, new HashMap<>(), sups);
            out.append("    (\"").append(e.getKey()).append("\", &[");
            out.append(Arrays.stream(c.getTypeParameters()).map(t -> "\"" + t.getName() + "\"").collect(Collectors.joining(", ")));
            out.append("], &[");
            out.append(sups.entrySet().stream()
                    .map(s -> "(\"" + s.getKey() + "\", &[" + s.getValue().stream().map(a -> "\"" + a + "\"").collect(Collectors.joining(", ")) + "])")
                    .collect(Collectors.joining(", ")));
            out.append("]),\n");
        }
        out.append("];\n");
        Files.writeString(Path.of("src/jdk_supertypes.rs"), out.toString());
    }

    static void add(Map<String, List<Class<?>>> bySimple, Class<?> c) {
        bySimple.computeIfAbsent(c.getSimpleName(), k -> new ArrayList<>()).add(c);
    }

    /// Walk `c`'s supertypes, writing each one's arguments through `env` (the
    /// substitution from a supertype's own type variables to text in terms of
    /// the root class).
    static void collect(Class<?> c, Map<String, String> env, Map<String, List<String>> out) {
        List<Type> direct = new ArrayList<>();
        if (c.getGenericSuperclass() != null) direct.add(c.getGenericSuperclass());
        direct.addAll(Arrays.asList(c.getGenericInterfaces()));
        for (Type t : direct) {
            Class<?> raw = t instanceof ParameterizedType p ? (Class<?>) p.getRawType() : (Class<?>) t;
            if (raw == Object.class) continue;
            List<String> argText = new ArrayList<>();
            Map<String, String> inner = new HashMap<>();
            TypeVariable<?>[] vars = raw.getTypeParameters();
            if (t instanceof ParameterizedType p) {
                Type[] actual = p.getActualTypeArguments();
                for (int i = 0; i < actual.length; i++) {
                    String a = render(actual[i], env);
                    argText.add(a);
                    inner.put(vars[i].getName(), a);
                }
            }
            out.putIfAbsent(raw.getSimpleName(), argText);
            collect(raw, inner, out);
        }
    }

    static String render(Type t, Map<String, String> env) {
        if (t instanceof Class<?> k) return k.getSimpleName();
        if (t instanceof TypeVariable<?> v) return env.getOrDefault(v.getName(), "#" + v.getName());
        return "?";
    }
}
