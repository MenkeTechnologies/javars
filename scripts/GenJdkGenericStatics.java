// Regenerate javars's table of the JDK's generic static methods from a real JDK.
//
//   JAVA_HOME=/path/to/jdk "$JAVA_HOME/bin/java" scripts/GenJdkGenericStatics.java
//
// run from the crate root. It writes src/jdk_generic_statics.rs: for every
// public static method of the public classes and interfaces in the packages
// below that declares type parameters and returns a parameterized type, the
// method's simple class name, name, parameter count, whether it is variable
// arity, and — per type argument of its return type — the name of the
// method's own type parameter standing there (`List.of` returns `List<E>`, so
// `E`), or "" where the argument is anything else.
//
// A call to one of these in an assignment or invocation context is a poly
// expression (JLS 15.12): `javac` infers it together with the call it is
// passed to, so a conflict in a type argument it supplies is reported against
// its own variable. The compiler reads this to name that variable as `javac`
// does; see `Compiler::nested_poly_var`.

import java.io.IOException;
import java.lang.reflect.*;
import java.net.URI;
import java.nio.file.*;
import java.util.*;
import java.util.stream.*;

public class GenJdkGenericStatics {
    static final String[] PACKAGES = {
        "java.lang", "java.util", "java.util.function", "java.util.stream",
    };

    public static void main(String[] args) throws Exception {
        FileSystem jrt = FileSystems.getFileSystem(URI.create("jrt:/"));
        // simple class name -> declaring classes, to drop names two packages share
        Map<String, Set<String>> owners = new TreeMap<>();
        TreeSet<String> rows = new TreeSet<>();
        for (String pkg : PACKAGES) {
            Path dir = jrt.getPath("/modules/java.base/" + pkg.replace('.', '/'));
            List<String> names;
            try (Stream<Path> s = Files.list(dir)) {
                names = s.map(p -> p.getFileName().toString())
                        .filter(n -> n.endsWith(".class") && !n.contains("$") && !n.equals("package-info.class"))
                        .map(n -> pkg + "." + n.substring(0, n.length() - 6))
                        .sorted()
                        .collect(Collectors.toList());
            }
            for (String n : names) {
                Class<?> c = Class.forName(n, false, ClassLoader.getSystemClassLoader());
                if (!Modifier.isPublic(c.getModifiers())) continue;
                owners.computeIfAbsent(c.getSimpleName(), k -> new TreeSet<>()).add(c.getName());
                for (Method m : c.getDeclaredMethods()) {
                    int mod = m.getModifiers();
                    if (!Modifier.isPublic(mod) || !Modifier.isStatic(mod) || m.isSynthetic()) continue;
                    if (m.getTypeParameters().length == 0) continue;
                    if (!(m.getGenericReturnType() instanceof ParameterizedType ret)) continue;
                    Set<String> own = Arrays.stream(m.getTypeParameters())
                            .map(TypeVariable::getName)
                            .collect(Collectors.toSet());
                    List<String> slots = new ArrayList<>();
                    boolean any = false;
                    for (Type a : ret.getActualTypeArguments()) {
                        if (a instanceof TypeVariable<?> v && own.contains(v.getName())) {
                            slots.add(v.getName());
                            any = true;
                        } else {
                            slots.add("");
                        }
                    }
                    if (!any) continue;
                    String vars = slots.stream().map(v -> "\"" + v + "\"").collect(Collectors.joining(", "));
                    rows.add(String.format("    (\"%s\", \"%s\", %d, %b, &[%s]),",
                            c.getSimpleName(), m.getName(), m.getParameterCount(), m.isVarArgs(), vars));
                }
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("//! Generated by `scripts/GenJdkGenericStatics.java` from ")
           .append(System.getProperty("java.vm.name")).append(' ')
           .append(System.getProperty("java.version")).append(" — do not edit.\n");
        out.append("//!\n//! Each entry is a public static JDK method that declares type parameters\n");
        out.append("//! and returns a parameterized type: its class's simple name, its name,\n");
        out.append("//! its parameter count, whether it is variable arity, and for each type\n");
        out.append("//! argument of its return type the method type parameter standing there\n");
        out.append("//! (`\"\"` for anything else).\n\n");
        out.append("/// One method: class, name, parameter count, variable arity, return slots.\n");
        out.append("pub type Entry = (&'static str, &'static str, usize, bool, &'static [&'static str]);\n\n");
        out.append("/// Every such method, sorted.\n#[rustfmt::skip]\npub static JDK_GENERIC_STATICS: &[Entry] = &[\n");
        for (String r : rows) {
            String cls = r.substring(r.indexOf('"') + 1, r.indexOf('"', r.indexOf('"') + 1));
            if (owners.getOrDefault(cls, Set.of()).size() > 1) continue;
            out.append(r).append('\n');
        }
        out.append("];\n");
        Files.writeString(Path.of("src/jdk_generic_statics.rs"), out.toString());
    }
}
