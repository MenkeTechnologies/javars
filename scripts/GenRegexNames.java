// Regenerate javars's tables of the names java.util.regex accepts in
// `\p{…}` / `\P{…}` from a real JDK.
//
//   JAVA_HOME=/path/to/jdk "$JAVA_HOME/bin/java" \
//       --add-opens java.base/java.lang=ALL-UNNAMED scripts/GenRegexNames.java
//
// run from the crate root. It writes src/regex_names.rs, which
// `src/regex_syntax.rs` reads to decide, as `Pattern.family` does, whether a
// property name exists:
//
// * BLOCKS — every key `Character.UnicodeBlock.forName` looks a name up by
//   (its private alias map, upper-cased with `Locale.US`);
// * SCRIPTS — every name `Character.UnicodeScript.forName` accepts (the enum
//   constants and its private alias map, upper-cased with `Locale.ENGLISH`);
// * PROPERTIES — the names `CharPredicates.forProperty` knows, matched
//   exactly (`\p{Lu}`, `\p{Alpha}`, `\p{javaLowerCase}`);
// * UNICODE_PROPERTIES — the binary properties `CharPredicates.forUnicodeProperty`
//   knows, matched upper-cased (`\p{IsAlphabetic}`, `\p{IsWhite_Space}`);
// * POSIX — the names `CharPredicates.forPOSIXName` knows under
//   `UNICODE_CHARACTER_CLASS`, matched upper-cased.
//
// The last three are `switch`es over strings in
// `java.util.regex.CharPredicates`, so their candidates are the string
// constants of that class file; each candidate is kept only when the real
// `Pattern.compile` accepts it in that position.

import java.io.*;
import java.lang.reflect.*;
import java.net.URI;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;
import java.util.stream.*;

public class GenRegexNames {
    public static void main(String[] args) throws Exception {
        TreeSet<String> blocks = new TreeSet<>(privateMapKeys(Character.UnicodeBlock.class, "map"));
        TreeSet<String> scripts = new TreeSet<>(privateMapKeys(Character.UnicodeScript.class, "aliases"));
        for (Character.UnicodeScript s : Character.UnicodeScript.values()) scripts.add(s.name());

        FileSystem jrt = FileSystems.getFileSystem(URI.create("jrt:/"));
        byte[] cls = Files.readAllBytes(jrt.getPath(
                "/modules/java.base/java/util/regex/CharPredicates.class"));
        TreeSet<String> candidates = stringConstants(cls);

        TreeSet<String> properties = new TreeSet<>();
        TreeSet<String> unicode = new TreeSet<>();
        TreeSet<String> posix = new TreeSet<>();
        for (String c : candidates) {
            if (c.isEmpty() || c.startsWith("In") || c.startsWith("Is") || c.indexOf('=') >= 0
                    || c.indexOf('}') >= 0 || c.chars().anyMatch(ch -> ch > 0x7e || ch < 0x21)) continue;
            if (accepts("\\p{" + c + "}", 0)) properties.add(c);
        }
        for (String c : candidates) {
            if (c.isEmpty() || c.indexOf('}') >= 0 || c.chars().anyMatch(ch -> ch > 0x7e || ch < 0x21)) continue;
            String up = c.toUpperCase(Locale.ROOT);
            String low = c.toLowerCase(Locale.ROOT);
            // `Is` + name tries forUnicodeProperty (upper-cased), then
            // forProperty, then the scripts: a lower-cased spelling that is
            // neither of the other two can only be accepted by the first.
            if (!properties.contains(low) && !scripts.contains(low.toUpperCase(Locale.ENGLISH))
                    && accepts("\\p{Is" + low + "}", 0)) unicode.add(up);
            if (!properties.contains(low) && accepts("\\p{" + low + "}", Pattern.UNICODE_CHARACTER_CLASS)) posix.add(up);
        }

        StringBuilder out = new StringBuilder();
        out.append("//! Generated by `scripts/GenRegexNames.java` from ")
           .append(System.getProperty("java.vm.name")).append(' ')
           .append(System.getProperty("java.version")).append(" — do not edit.\n");
        out.append("//!\n//! The names `java.util.regex.Pattern` accepts in a `\\p{…}` property,\n");
        out.append("//! each table sorted: see the generator for how each is matched.\n\n");
        table(out, "BLOCKS", "`Character.UnicodeBlock.forName`'s keys, upper-cased (`Locale.US`).", blocks);
        table(out, "SCRIPTS", "`Character.UnicodeScript.forName`'s names, upper-cased (`Locale.ENGLISH`).", scripts);
        table(out, "PROPERTIES", "`CharPredicates.forProperty`'s names, matched exactly.", properties);
        table(out, "UNICODE_PROPERTIES", "`CharPredicates.forUnicodeProperty`'s names, upper-cased.", unicode);
        table(out, "POSIX", "`CharPredicates.forPOSIXName`'s names, upper-cased.", posix);
        Files.writeString(Path.of("src/regex_names.rs"), out.toString());
    }

    static boolean accepts(String regex, int flags) {
        try {
            Pattern.compile(regex, flags);
            return true;
        } catch (PatternSyntaxException e) {
            return false;
        }
    }

    @SuppressWarnings("unchecked")
    static Set<String> privateMapKeys(Class<?> c, String field) throws Exception {
        Field f = c.getDeclaredField(field);
        f.setAccessible(true);
        return ((Map<String, ?>) f.get(null)).keySet();
    }

    static void table(StringBuilder out, String name, String doc, Set<String> names) {
        out.append("/// ").append(doc).append('\n');
        out.append("#[rustfmt::skip]\npub static ").append(name).append(": &[&str] = &[\n");
        for (String n : names) out.append("    \"").append(n.replace("\\", "\\\\").replace("\"", "\\\"")).append("\",\n");
        out.append("];\n\n");
    }

    /// The CONSTANT_String entries of a class file.
    static TreeSet<String> stringConstants(byte[] b) throws IOException {
        DataInputStream in = new DataInputStream(new ByteArrayInputStream(b));
        in.readInt();
        in.readUnsignedShort();
        in.readUnsignedShort();
        int n = in.readUnsignedShort();
        String[] utf8 = new String[n];
        List<Integer> strings = new ArrayList<>();
        for (int i = 1; i < n; i++) {
            int tag = in.readUnsignedByte();
            switch (tag) {
                case 1 -> utf8[i] = in.readUTF();
                case 3, 4 -> in.readInt();
                case 5, 6 -> { in.readLong(); i++; }
                case 7, 16, 19, 20 -> in.readUnsignedShort();
                case 8 -> strings.add(in.readUnsignedShort());
                case 9, 10, 11, 12, 17, 18 -> { in.readUnsignedShort(); in.readUnsignedShort(); }
                case 15 -> { in.readUnsignedByte(); in.readUnsignedShort(); }
                default -> throw new IOException("constant pool tag " + tag);
            }
        }
        TreeSet<String> out = new TreeSet<>();
        for (int s : strings) out.add(utf8[s]);
        return out;
    }
}
